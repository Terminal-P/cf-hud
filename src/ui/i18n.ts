const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, zh };

/** A bound translator, cheap to pass down as a prop. */
export type TFunction = (key: TranslationKey, params?: Params) => string;

function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

export function t(language: Language, key: TranslationKey, params?: Params): string {
  const dictionary = dictionaries[language] ?? en;
  return interpolate(dictionary[key] ?? en[key], params);
}

export function createTranslator(language: Language): TFunction {
  return (key, params) => t(language, key, params);
}

